import numpy as np
import pandas as pd
import torch
from datasets import Dataset, load_dataset
from sklearn.metrics import accuracy_score, f1_score
from transformers import (
    AutoTokenizer,
    AutoModelForSequenceClassification,
    DataCollatorWithPadding,
    TrainingArguments,
    Trainer,
)

MODEL_NAME = "distilbert-base-uncased"
use_gpu = torch.cuda.is_available()
print("GPU available:", use_gpu)

N_TRAIN = 3000 if use_gpu else 800
N_TEST = 1000 if use_gpu else 300
MAX_LEN = 128

# ---- 1. Data: try 3 sources in order ----
def get_data():
    # Source A: official dataset id
    try:
        ds = load_dataset("stanfordnlp/imdb")
        print("Loaded from stanfordnlp/imdb")
        return ds["train"].to_pandas(), ds["test"].to_pandas()
    except Exception as e:
        print("Source A failed:", repr(e)[:150])
    # Source B: direct parquet
    try:
        base = "https://huggingface.co/datasets/stanfordnlp/imdb/resolve/main/plain_text/"
        tr = pd.read_parquet(base + "train-00000-of-00001.parquet")
        te = pd.read_parquet(base + "test-00000-of-00001.parquet")
        print("Loaded from parquet URL")
        return tr, te
    except Exception as e:
        print("Source B failed:", repr(e)[:150])
    # Source C: tiny built-in dataset so the pipeline still runs
    print("Using tiny built-in dataset (demo only)")
    pos = ["I loved this movie, it was fantastic", "Great acting and a wonderful story",
           "Absolutely brilliant, highly recommended", "A beautiful and moving film",
           "Superb direction, I enjoyed every minute"] * 40
    neg = ["Terrible plot and awful acting", "I hated this movie, a total waste of time",
           "Boring, slow and badly written", "Worst film I have seen this year",
           "Disappointing and painfully dull"] * 40
    df = pd.DataFrame({"text": pos + neg, "label": [1]*len(pos) + [0]*len(neg)})
    df = df.sample(frac=1, random_state=42).reset_index(drop=True)
    return df.iloc[:300], df.iloc[300:]

train_df, test_df = get_data()
train_df = train_df.sample(min(N_TRAIN, len(train_df)), random_state=42).reset_index(drop=True)
test_df = test_df.sample(min(N_TEST, len(test_df)), random_state=42).reset_index(drop=True)

train_ds = Dataset.from_pandas(train_df[["text", "label"]])
test_ds = Dataset.from_pandas(test_df[["text", "label"]])

# ---- 2. Tokenize ----
tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

def tokenize(batch):
    return tokenizer(batch["text"], truncation=True, max_length=MAX_LEN)

train_ds = train_ds.map(tokenize, batched=True, remove_columns=["text"])
test_ds = test_ds.map(tokenize, batched=True, remove_columns=["text"])
collator = DataCollatorWithPadding(tokenizer=tokenizer)

# ---- 3. Model ----
model = AutoModelForSequenceClassification.from_pretrained(
    MODEL_NAME, num_labels=2,
    id2label={0: "NEGATIVE", 1: "POSITIVE"},
    label2id={"NEGATIVE": 0, "POSITIVE": 1},
)

# ---- 4. Metrics ----
def compute_metrics(p):
    preds = np.argmax(p.predictions, axis=-1)
    return {
        "accuracy": accuracy_score(p.label_ids, preds),
        "f1": f1_score(p.label_ids, preds, average="weighted"),
    }

# ---- 5. Train (only basic, stable arguments) ----
args = TrainingArguments(
    output_dir="out",
    learning_rate=3e-5,
    per_device_train_batch_size=32,
    per_device_eval_batch_size=64,
    num_train_epochs=1,
    save_strategy="no",
    logging_steps=20,
    fp16=use_gpu,
    report_to="none",
)

trainer = Trainer(
    model=model,
    args=args,
    train_dataset=train_ds,
    eval_dataset=test_ds,
    data_collator=collator,
    compute_metrics=compute_metrics,
)

trainer.train()
print(trainer.evaluate())

# ---- 6. Inference (no pipeline, avoids version issues) ----
def predict(text):
    model.eval()
    enc = tokenizer(text, return_tensors="pt", truncation=True, max_length=MAX_LEN).to(model.device)
    with torch.no_grad():
        probs = torch.softmax(model(**enc).logits, dim=-1)[0]
    i = int(probs.argmax())
    return model.config.id2label[i], round(float(probs[i]), 4)

print(predict("This movie was absolutely fantastic!"))
print(predict("Terrible plot and awful acting."))