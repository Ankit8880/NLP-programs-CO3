"""Now, let's load the necessary models and tokenizers, define our input sentences, and write a helper function to extract the embeddings."""

import torch
from transformers import BertTokenizer, BertModel, GPT2Tokenizer, GPT2Model
import numpy as np

# Check if GPU is available
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print(f"Using device: {device}")

# Load pre-trained models and tokenizers
bert_tokenizer = BertTokenizer.from_pretrained('bert-base-uncased')
bert_model = BertModel.from_pretrained('bert-base-uncased').to(device)

gpt2_tokenizer = GPT2Tokenizer.from_pretrained('gpt2')
gpt2_tokenizer.pad_token = gpt2_tokenizer.eos_token
gpt2_model = GPT2Model.from_pretrained('gpt2').to(device)

# Sample sentences to embed
sentences = [
    "Deep learning enables powerful representation learning.",
    "Artificial intelligence is transforming industries.",
    "We are extracting sentence embeddings using pre-trained transformers."
]

"""### 1. BERT Embeddings
For BERT, we typically obtain sentence representations either by extracting the `[CLS]` token's embedding (the first token) or by taking the average (mean pooling) of all token embeddings in the last hidden state.
"""

def get_bert_embeddings(sentences, model, tokenizer, pooling='mean'):
    model.eval()
    embeddings = []

    for sentence in sentences:
        # Tokenize and prepare input
        inputs = tokenizer(sentence, return_tensors='pt', padding=True, truncation=True, max_length=128).to(device)

        with torch.no_grad():
            outputs = model(**inputs)

        # Get the last hidden state: shape [batch_size, sequence_length, hidden_size]
        last_hidden_state = outputs.last_hidden_state

        if pooling == 'cls':
            # [CLS] token is at index 0
            embedding = last_hidden_state[0, 0, :].cpu().numpy()
        elif pooling == 'mean':
            # Average along the sequence length dimension
            embedding = torch.mean(last_hidden_state, dim=1).squeeze().cpu().numpy()

        embeddings.append(embedding)

    return np.array(embeddings)

bert_embeds = get_bert_embeddings(sentences, bert_model, bert_tokenizer, pooling='mean')
print("BERT Mean-Pooled Embeddings Shape:", bert_embeds.shape)

"""### 2. GPT-2 Embeddings
GPT-2 is an autoregressive (causal) decoder model. Unlike BERT, it doesn't have a special `[CLS]` token. A common approach is to take the mean of all token hidden states or target the last token's representation.
"""

def get_gpt2_embeddings(sentences, model, tokenizer, pooling='mean'):
    model.eval()
    embeddings = []

    for sentence in sentences:
        inputs = tokenizer(sentence, return_tensors='pt', padding=True, truncation=True, max_length=128).to(device)

        with torch.no_grad():
            outputs = model(**inputs)

        last_hidden_state = outputs.last_hidden_state

        if pooling == 'last':
            # Extract the vector corresponding to the last token in the sequence
            embedding = last_hidden_state[0, -1, :].cpu().numpy()
        elif pooling == 'mean':
            # Mean pool across sequence tokens
            embedding = torch.mean(last_hidden_state, dim=1).squeeze().cpu().numpy()

        embeddings.append(embedding)

    return np.array(embeddings)

gpt2_embeds = get_gpt2_embeddings(sentences, gpt2_model, gpt2_tokenizer, pooling='mean')
print("GPT-2 Mean-Pooled Embeddings Shape:", gpt2_embeds.shape)